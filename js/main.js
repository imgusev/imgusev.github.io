const STORAGE_LANG = 'imgusev:lang';
const STORAGE_THEME = 'imgusev:theme';

function applyTranslations(lang) {
  const dict = translations[lang] || translations.ru;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });
  const label = document.querySelector('[data-lang-label]');
  if (label) label.textContent = lang === 'ru' ? 'EN' : 'RU';
}

function initLang() {
  const saved = localStorage.getItem(STORAGE_LANG);
  const browser = (navigator.language || 'ru').toLowerCase().startsWith('ru')
    ? 'ru'
    : 'en';
  const initial = saved || browser;
  applyTranslations(initial);

  document.querySelector('[data-lang-toggle]')?.addEventListener('click', () => {
    const current = document.documentElement.lang === 'ru' ? 'ru' : 'en';
    const next = current === 'ru' ? 'en' : 'ru';
    localStorage.setItem(STORAGE_LANG, next);
    applyTranslations(next);
  });
}

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
}

function initTheme() {
  const saved = localStorage.getItem(STORAGE_THEME);
  const prefersDark =
    window.matchMedia &&
    window.matchMedia('(prefers-color-scheme: dark)').matches;
  const initial = saved || (prefersDark ? 'dark' : 'light');
  applyTheme(initial);

  document.querySelector('[data-theme-toggle]')?.addEventListener('click', () => {
    const current = document.documentElement.getAttribute('data-theme');
    const next = current === 'dark' ? 'light' : 'dark';
    localStorage.setItem(STORAGE_THEME, next);
    applyTheme(next);
  });
}

function initBurger() {
  const burger = document.querySelector('[data-burger]');
  const list = document.querySelector('[data-nav-list]');
  if (!burger || !list) return;

  const close = () => {
    burger.setAttribute('aria-expanded', 'false');
    list.classList.remove('is-open');
  };

  burger.addEventListener('click', () => {
    const expanded = burger.getAttribute('aria-expanded') === 'true';
    burger.setAttribute('aria-expanded', String(!expanded));
    list.classList.toggle('is-open', !expanded);
  });

  list.addEventListener('click', (e) => {
    if (e.target.tagName === 'A') close();
  });
}

function initYear() {
  const el = document.getElementById('year');
  if (el) el.textContent = new Date().getFullYear();
}

document.addEventListener('DOMContentLoaded', () => {
  initTheme();
  initLang();
  initBurger();
  initYear();
});
